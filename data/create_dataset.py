def generate_dataset(output_path="multilingual_sentiment_dataset.csv", samples_per_lang=500):
    rows = []
    labels = ["positive", "negative", "neutral"]
    lang_codes = {"english": "en", "hindi": "hi", "spanish": "es", "french": "fr"}

    for lang, label_data in SAMPLES.items():
        per_label = samples_per_lang // 3
        remainder = samples_per_lang % 3

        for i, label in enumerate(labels):
            base_texts = label_data[label]
            count = per_label + (1 if i < remainder else 0)
            texts = []
            while len(texts) < count:
                texts.extend(base_texts)
            texts = texts[:count]

            for text in texts:
                rows.append({
                    "text": text,
                    "language": lang,
                    "language_code": lang_codes[lang],
                    "sentiment": label,
                    "label": labels.index(label),
                })

    df = pd.DataFrame(rows)
    df = df.sample(frac=1, random_state=42).reset_index(drop=True)

    os.makedirs(os.path.dirname(output_path) if os.path.dirname(output_path) else ".", exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"Dataset saved: {output_path}")
    print(f"Total samples: {len(df)}")
    print(df.groupby(["language", "sentiment"]).size().to_string())
    return df


